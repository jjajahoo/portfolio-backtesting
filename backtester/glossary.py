def sharpe_grade(sharpe: float) -> str:
    if sharpe < 0:
        return "예금보다 못했어요"
    if sharpe < 0.5:
        return "아쉬운 편이에요"
    if sharpe < 1:
        return "괜찮은 편이에요"
    return "훌륭한 편이에요 (오랜 기간 1을 넘기긴 어려워요)"


def explain(
    m: Metrics,
    currency: str,
    risk_free: float,
    bm: Metrics | None = None,
    bench_name: str | None = None,
) -> list[tuple[str, str]]:
    """실제 결과 숫자를 넣은 설명 목록. (제목, 마크다운 본문)"""
    out: list[tuple[str, str]] = []
    has_bench = bm is not None and bench_name

    # 최종 금액
    text = (
        f"**{ym(m.start)}에 {money(m.initial, currency)}을 넣고 그대로 뒀다면, "
        f"{ym(m.end)}에는 {money(m.final, currency)}이 됐어요.** "
        f"원금의 {m.final / m.initial:.1f}배예요 (총 수익률 {pct(m.total_return, signed=True)})."
    )
    if has_bench:
        text += f"\n\n같은 돈을 {bench_name}에 넣었다면 {money(bm.final, currency)}이었어요."
    out.append(("💰 얼마가 됐나요?", text))

    # CAGR
    text = f"매년 평균 **{pct(m.cagr)}씩** 불어난 셈이에요. "
    text += f"해마다 오르내렸지만, '매년 똑같이 {pct(m.cagr)}씩 올랐다'고 치면 같은 결과가 나와요."
    if m.cagr > 0:
        double = math.log(2) / math.log(1 + m.cagr)
        text += f"\n\n이 속도라면 돈이 **2배가 되는 데 약 {double:.0f}년** 걸려요."
    text += f" 예금 금리 {pct(risk_free)}와 비교해 보세요."
    if has_bench:
        diff = m.cagr - bm.cagr
        word = "높았어요" if diff >= 0 else "낮았어요"
        text += f"\n\n{bench_name}의 연평균 수익률 {pct(bm.cagr)}보다 1년에 {abs(diff) * 100:.1f}%p {word}."
    out.append(("📈 연평균 수익률 (CAGR)", text))

    # MDD
    p = m.max_drawdown_period
    if p is not None:
        example = 10_000_000 if currency == "KRW" else 10_000
        text = (
            f"가장 힘들었던 때는 **{ym(p.peak)} ~ {ym(p.trough)}**이에요. "
            f"고점보다 **{pct(m.max_drawdown)}까지** 떨어졌어요. "
            f"그 고점에 계좌에 {money(example, currency)}이 있었다면 "
            f"**{money(example * (1 + m.max_drawdown), currency)}**까지 줄어든 거예요."
        )
        if p.recovery is not None:
            text += f"\n\n다시 고점을 되찾은 건 {ym(p.recovery)}, 고점부터 **{duration(p.days(m.end))}** 걸렸어요."
        else:
            text += "\n\n그리고 기간 마지막 날까지 아직 그 고점을 되찾지 못했어요."
        if has_bench:
            text += f"\n\n{bench_name}의 최대 낙폭은 {pct(bm.max_drawdown)}였어요."
        text += "\n\n💡 이 하락을 겪는 동안 팔지 않고 버틸 수 있을지 스스로에게 물어보세요. 백테스트에서 가장 중요한 숫자예요."
        out.append(("📉 최대 낙폭 (MDD)", text))

    # 가장 긴 회복 기간 (MDD 구간과 다를 때만)
    q = m.longest_drawdown
    if q is not None and p is not None and q.peak != p.peak:
        state = f"{ym(q.recovery)}에 회복했어요" if q.recovery else "아직 회복 중이에요"
        text = (
            f"낙폭이 가장 깊었던 때와는 별개로, 가장 오래 '물려 있던' 기간은 **{ym(q.peak)}부터 "
            f"{duration(q.days(m.end))}**이에요 ({state}). 그동안 최대 {pct(q.depth)}까지 빠져 있었어요."
        )
        out.append(("⏳ 가장 긴 회복 기간", text))

    # 변동성
    if m.volatility is not None:
        lo, hi = m.cagr - m.volatility, m.cagr + m.volatility
        text = (
            f"1년 수익률이 평균에서 보통 **±{pct(m.volatility)}** 정도 출렁였다는 뜻이에요. "
            f"대략 **3년 중 2년은 {pct(lo)} ~ {pct(hi)}** 사이였다고 생각하면 돼요."
        )
        if has_bench and bm.volatility is not None:
            word = "덜" if m.volatility < bm.volatility else "더"
            text += f"\n\n{bench_name}의 변동성 {pct(bm.volatility)}보다 {word} 출렁였어요."
        out.append(("🎢 변동성", text))

    # 샤프 비율
    if m.sharpe is not None:
        text = (
            f"샤프 비율 **{ratio(m.sharpe)}** → {sharpe_grade(m.sharpe)}\n\n"
            f"변동성(마음고생) 1%를 견딜 때마다 예금({pct(risk_free)})보다 수익률이 {ratio(m.sharpe)}%p씩 "
            "더 높았다는 뜻이에요."
        )
        if has_bench and bm.sharpe is not None:
            word = "좋았어요" if m.sharpe >= bm.sharpe else "나빴어요"
            text += f"\n\n{bench_name}의 샤프 비율 {ratio(bm.sharpe)}보다 위험 대비 효율이 {word}."
        out.append(("⚖️ 샤프 비율", text))

    # 최고/최악의 해
    if m.best_year and m.worst_year:
        text = (
            f"- 가장 좋았던 해: **{m.best_year[0]}년 {pct(m.best_year[1], signed=True)}**\n"
            f"- 가장 나빴던 해: **{m.worst_year[0]}년 {pct(m.worst_year[1], signed=True)}**"
        )
        partial = {m.start.year, m.end.year} & {m.best_year[0], m.worst_year[0]}
        if partial:
            years = ", ".join(f"{y}년" for y in sorted(partial))
            text += f"\n\n({years}은 1년이 다 안 되는 기간이에요.)"
        out.append(("📅 최고의 해 / 최악의 해", text))

    return out
